def upsert_papers(conn: sqlite3.Connection, rows: Iterable[dict[str, Any]]) -> int:
    """Insert or merge papers. Existing non-null columns are only overwritten by
    non-null incoming values, so enrichment never gets clobbered by a re-crawl."""
    cols = ",".join(PAPER_FIELDS)
    placeholders = ",".join("?" for _ in PAPER_FIELDS)
    updates = ",".join(f"{c}=COALESCE(excluded.{c}, papers.{c})" for c in PAPER_FIELDS if c != "id")
    sql = (
        f"INSERT INTO papers ({cols}) VALUES ({placeholders}) "
        f"ON CONFLICT(id) DO UPDATE SET {updates}"
    )
    n = 0
    batch = []
    for r in rows:
        r.setdefault("title_key", title_key(r.get("title", "")))
        r.setdefault("crawled_at", now())
        # NOT NULL columns: an explicit None from a partial row would violate the
        # constraint, and COALESCE on update cannot rescue a failed insert.
        if r.get("authors_json") is None:
            r["authors_json"] = "[]"
        if r.get("is_canon") is None:
            r["is_canon"] = 0
        batch.append(tuple(r.get(c) for c in PAPER_FIELDS))
        n += 1
        if len(batch) >= 500:
            conn.executemany(sql, batch)
            batch.clear()
    if batch:
        conn.executemany(sql, batch)
    return n


def get_kv(conn: sqlite3.Connection, key: str, default: Any = None) -> Any:
    row = conn.execute("SELECT value FROM kv WHERE key=?", (key,)).fetchone()
    return json.loads(row["value"]) if row else default


def set_kv(conn: sqlite3.Connection, key: str, value: Any) -> None:
    conn.execute(
        "INSERT INTO kv(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
        (key, json.dumps(value)),
    )


def counts_by_venue_year(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    return conn.execute(
        "SELECT venue, year, COUNT(*) AS n, "
        "SUM(citation_count IS NOT NULL) AS enriched, "
        "SUM(score IS NOT NULL) AS scored "
        "FROM papers GROUP BY venue, year ORDER BY year DESC, venue"
    ).fetchall()
