def now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def title_key(title: str) -> str:
    """Normalised title used to detect the same paper arriving from two sources."""
    return "".join(ch for ch in title.lower() if ch.isalnum())[:120]


def search_papers(conn: sqlite3.Connection, text: str, limit: int = 20) -> list[sqlite3.Row]:
    """Find papers anywhere in the corpus, not just the ranked queue.

    The queue is ~5,000 of ~63,000 papers. Adding one by hand means first finding it
    among the other 58,000, which the reader's own search cannot do -- it filters the
    rows already on screen.
    """
    key = title_key(text)
    rows = conn.execute(
        "SELECT p.*, q.state, q.role FROM papers p LEFT JOIN queue q ON q.paper_id = p.id "
        "WHERE p.title_key LIKE ? ORDER BY p.score IS NULL, p.score DESC, "
        "p.citation_count DESC LIMIT ?",
        (f"%{key}%", limit),
    ).fetchall()
    if rows or not key:
        return rows
    # Nothing matched as one run-together string: fall back to every word appearing
    # somewhere in the title, which is what a half-remembered title looks like.
    words = [w for w in re.split(r"\W+", text.lower()) if len(w) > 2][:6]
    if not words:
        return []
    where = " AND ".join("LOWER(p.title) LIKE ?" for _ in words)
    return conn.execute(
        f"SELECT p.*, q.state, q.role FROM papers p LEFT JOIN queue q ON q.paper_id = p.id "
        f"WHERE {where} ORDER BY p.score IS NULL, p.score DESC, p.citation_count DESC "
        f"LIMIT ?",
        (*[f"%{w}%" for w in words], limit),
    ).fetchall()


# Databases this process has already prepared. The data folders and WAL mode stay
# once made, and making sure of them on every connection doubled its cost: the
# window opens dozens per paper.
_prepared: set[str] = set()


@contextmanager
def connect(*, timeout: float = 30, path=None) -> Iterator[sqlite3.Connection]:
    target = str(path or DB_PATH)
    if target not in _prepared:
        ensure_dirs()
    conn = sqlite3.connect(target, timeout=timeout)
    conn.row_factory = sqlite3.Row
    if target not in _prepared:
        conn.execute("PRAGMA journal_mode=WAL")
        _prepared.add(target)
    conn.execute("PRAGMA synchronous=NORMAL")
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def init_db() -> None:
    with connect() as conn:
        conn.executescript(SCHEMA)
        _migrate(conn)


def _migrate(conn: sqlite3.Connection) -> None:
    """Columns added after a database already existed. CREATE TABLE IF NOT EXISTS
    leaves an older table alone, so new columns have to be added explicitly."""
    if "spec" not in {r[1] for r in conn.execute("PRAGMA table_info(dives)")}:
        conn.execute("ALTER TABLE dives ADD COLUMN spec TEXT")

    have = {r[1] for r in conn.execute("PRAGMA table_info(notes)")}
    for column, ddl in (
        ("kind", "TEXT NOT NULL DEFAULT 'note'"),
        ("page", "INTEGER"),
        ("anchor", "TEXT"),
    ):
        if column not in have:
            conn.execute(f"ALTER TABLE notes ADD COLUMN {column} {ddl}")

    have = {r[1] for r in conn.execute("PRAGMA table_info(chat)")}
    for column, ddl in (("page", "INTEGER"), ("anchor", "TEXT")):
        if column not in have:
            conn.execute(f"ALTER TABLE chat ADD COLUMN {column} {ddl}")

    have = {r[1] for r in conn.execute("PRAGMA table_info(cites)")}
    for column, ddl in (
        ("doi", "TEXT"),
        ("basis", "TEXT NOT NULL DEFAULT 'context'"),
        ("spec", "TEXT"),
        ("edited", "INTEGER NOT NULL DEFAULT 0"),
    ):
        if column not in have:
            conn.execute(f"ALTER TABLE cites ADD COLUMN {column} {ddl}")

    # An empty set means the table is not there yet, and the schema will create it
    # with every column.
    have = {r[1] for r in conn.execute("PRAGMA table_info(followups)")}
    for column, ddl in () if not have else (
        ("relation", "TEXT"),
        ("contexts_json", "TEXT"),
        ("arxiv_id", "TEXT"),
        ("edited", "INTEGER NOT NULL DEFAULT 0"),
    ):
        if column not in have:
            conn.execute(f"ALTER TABLE followups ADD COLUMN {column} {ddl}")


